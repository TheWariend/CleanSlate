import { readFile, writeFile } from 'node:fs/promises';

const packageUrl = new URL('../package.json', import.meta.url);
const outputUrl = new URL('../src/node/externalAgents/generatedSdkVersion.ts', import.meta.url);
const packageMetadata = JSON.parse(await readFile(packageUrl, 'utf8'));

if (typeof packageMetadata.version !== 'string' || !packageMetadata.version.trim()) {
	throw new Error('The CleanSlate SDK package has no version.');
}

const source = `/* This file is generated by scripts/write-sdk-version.mjs. Do not edit. */\nexport const CLEANSLATE_SDK_VERSION = ${JSON.stringify(packageMetadata.version)};\n`;
await writeFile(outputUrl, source);
